import FS from "node:fs/promises";
import Path from "node:path";

import type { ServerResponse } from "node:http";
import type { Plugin } from "vite";

/**
 * Writes `dist/_headers` for Cloudflare Pages from the config in `vite.config.js`, and sends the same
 * headers on `vite preview` - which sends `no-cache` for everything of its own accord, so the rules
 * would otherwise only be visible after a deploy.
 *
 * List it after the staging pass and the prerender: it describes their output, and it fails the build
 * when a path served as immutable holds a file whose name is not a hash.
 */

/** The file Cloudflare Pages reads out of the build output to set a static asset's headers. */
const HEADERS_FILE = "_headers";

/** One path, and what a request for it is served with. */
export interface Rule {
  /** A path, or a path with a trailing `*` to cover everything under it. */
  path: string;
  cache: string;
}

/** The caching config, as `vite.config.js` declares it. */
export interface CacheOptions {
  /** What a page is served with. */
  page: string;
  /** Every path that is not a page. First match wins. */
  rules: Rule[];
}

/** A content hash as the bundler writes it: `category-LUucyYPK.css`, `button-BIzQie78.js.map`. */
const FINGERPRINT = /-[A-Za-z0-9_-]{8}\.[A-Za-z0-9.]+$/;

export function isFingerprinted(file: string): boolean {
  return FINGERPRINT.test(file);
}

/** `*` is only ever a trailing wildcard here, so matching is all there is to it. */
function matches(pattern: string, pathname: string): boolean {
  return pattern.endsWith("*") ? pathname.startsWith(pattern.slice(0, -1)) : pathname === pattern;
}

/** The rule covering a pathname, or undefined when it is a page. */
export function ruleFor(rules: Rule[], pathname: string): Rule | undefined {
  return rules.find((rule) => matches(rule.path, pathname));
}

/** The directory a rule covers, for the guard to walk: `/explore/dist/chunks/*` -> `explore/dist/chunks` */
function directoryOf(rule: Rule): string {
  return rule.path.slice(1).replace(/\*$/, "");
}

/**
 * Whether a rule promises the file never has to be asked for again. That is only honest for a name
 * that changes with the content, so these are the rules the build checks.
 */
function isImmutable(rule: Rule): boolean {
  return rule.cache.includes("immutable");
}

/** Every file under `dir`, as a path relative to `outDir`. */
async function walk(outDir: string, dir: string): Promise<string[]> {
  let entries;

  try {
    entries = await FS.readdir(Path.join(outDir, dir), { withFileTypes: true });
  } catch {
    return []; // Not there: a build that emitted nothing under this directory.
  }

  const files: string[] = [];

  for (const entry of entries) {
    const path = Path.join(dir, entry.name);

    if (entry.isDirectory()) files.push(...(await walk(outDir, path)));
    else if (entry.isFile()) files.push(path);
  }

  return files;
}

/** The urls the built pages answer: `products.html` is `/products`. */
export async function pagesIn(outDir: string): Promise<string[]> {
  const pages = (await walk(outDir, ".")).filter((file) => file.endsWith(".html"));

  return pages.map((file) => `/${file.replace(/(index)?\.html$/, "")}`).sort();
}

/** The `_headers` file: a block per rule, then a block per page. */
export function headersFile(pages: string[], { page, rules }: CacheOptions): string {
  const block = (path: string, cache: string) => `${path}\n  Cache-Control: ${cache}`;
  const blocks = [...rules.map((rule) => block(rule.path, rule.cache)), ...pages.map((url) => block(url, page))];

  return [
    "# Generated by scripts/cache-headers.ts - edit the CACHE config in vite.config.js instead.",
    "# A path that is neither listed here nor a page keeps Cloudflare Pages' own default.",
    "",
    blocks.join("\n\n"),
    "",
  ].join("\n");
}

/** Fails the build when a path served as immutable holds a file whose name is not a hash. */
export async function checkFingerprinted(outDir: string, rules: Rule[]): Promise<string[]> {
  const dirs = rules.filter(isImmutable).map((rule) => directoryOf(rule));
  const files = (await Promise.all(dirs.map((dir) => walk(outDir, dir)))).flat();
  const bad = files.find((file) => !isFingerprinted(Path.basename(file)));

  if (bad) throw new Error(`${bad} is served immutable but carries no content hash in its name.`);

  return files;
}

/**
 * Vite's preview static middleware sets `Cache-Control` itself, after this, as it sends the file -
 * so ours goes on first, and every later write to that header is dropped.
 */
function pinCacheControl(res: ServerResponse, cache: string): void {
  const setHeader = res.setHeader.bind(res);

  setHeader("Cache-Control", cache);
  res.setHeader = ((name: string, value: string | number | readonly string[]) =>
    name.toLowerCase() === "cache-control" ? res : setHeader(name, value)) as typeof res.setHeader;
}

export function cacheHeaders(options: CacheOptions): Plugin {
  let outDir = "";

  return {
    name: "shell:cache-headers",
    // `apply: "build"` would leave the plugin out of `vite preview`.
    apply: (_, env) => env.command === "build" || env.isPreview === true,
    configResolved(config) {
      outDir = Path.resolve(config.root, config.build.outDir);
    },
    async closeBundle() {
      const pages = await pagesIn(outDir);
      const files = await checkFingerprinted(outDir, options.rules);

      await FS.writeFile(Path.join(outDir, HEADERS_FILE), headersFile(pages, options), "utf8");

      // eslint-disable-next-line no-console
      console.log(`  ${files.length} fingerprinted file(s), ${pages.length} page(s) -> ${HEADERS_FILE}`);
    },
    configurePreviewServer(server) {
      server.middlewares.use((req, res, next) => {
        const { pathname } = new URL(req.url ?? "/", "http://localhost");

        pinCacheControl(res, ruleFor(options.rules, decodeURIComponent(pathname))?.cache ?? options.page);

        next();
      });
    },
  };
}

export default cacheHeaders;
